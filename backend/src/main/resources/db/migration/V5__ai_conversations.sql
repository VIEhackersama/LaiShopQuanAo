CREATE TABLE ai_conversations (
    id uuid PRIMARY KEY,
    customer_id bigint REFERENCES customers,
    search_session varchar(80) NOT NULL,
    version bigint NOT NULL,
    state jsonb NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE ai_messages (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id uuid NOT NULL REFERENCES ai_conversations ON DELETE CASCADE,
    role varchar(20) NOT NULL CHECK(role IN ('user','assistant')),
    content varchar(2000) NOT NULL,
    query_id bigint REFERENCES search_queries ON DELETE SET NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ai_conversation_retention_idx ON ai_conversations(updated_at);
CREATE INDEX ai_message_conversation_idx ON ai_messages(conversation_id,id);
